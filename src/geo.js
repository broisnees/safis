      if (!pieces.length || s.color === false) return;
      clipped(() => {
        ctx.beginPath();
        trace(pieces, false);
        if (s.alpha != null) ctx.globalAlpha = s.alpha;
        ctx.strokeStyle = C(s.color ?? "ink");
        ctx.lineWidth = s.width ?? 1;
        ctx.lineJoin = ctx.lineCap = "round";
        ctx.setLineDash(s.dash ?? []);
        ctx.stroke();
      });
